const CATALOGS = Object.freeze({ en: EN, ko: KO, ja: JA, 'zh-TW': ZH_TW, nb: NB, de: DE });

/** Supported UI / output languages, each labelled in its own language. */
export const LANGUAGE_OPTIONS = Object.freeze([
  new LanguageOption({ code: 'auto', label: '' }),
  new LanguageOption({ code: 'ko', label: '한국어' }),
  new LanguageOption({ code: 'en', label: 'English' }),
  new LanguageOption({ code: 'ja', label: '日本語' }),
  new LanguageOption({ code: 'zh-TW', label: '繁體中文' }),
  new LanguageOption({ code: 'nb', label: 'Norsk' }),
  new LanguageOption({ code: 'de', label: 'Deutsch' }),
]);

/** Maps a preference ("auto" or a code) plus the browser language to a supported code. */
export function resolveLanguage(preference, browserLanguage) {
  if (preference && preference !== 'auto' && CATALOGS[preference]) return preference;
  const tag = String(browserLanguage ?? 'en');
  if (/^zh/i.test(tag)) return 'zh-TW';
  if (/^(nb|nn|no)\b/i.test(tag)) return 'nb';
  const base = tag.split('-')[0].toLowerCase();
  return CATALOGS[base] ? base : 'en';
}

/**
 * Looks up UI text for one language with "{name}" placeholders, falling back
 * to English. The root controller switches the language with use().
 */
export class Translator {
  #language = 'en';

  get language() {
    return this.#language;
  }

  use(language) {
    this.#language = CATALOGS[language] ? language : 'en';
  }

  has(key) {
    return key in CATALOGS[this.#language] || key in EN;
  }

  t(key, params = {}) {
    const template = CATALOGS[this.#language][key] ?? EN[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
  }
}
